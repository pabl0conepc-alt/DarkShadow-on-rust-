#!/usr/bin/env bash
# Regenerates src/icons_data.rs from Material Symbols Rounded (outlined + filled, 24px, weight 400).
# Add a name to ICONS below and run: tools/fetch-icons.sh
set -euo pipefail
cd "$(dirname "$0")/.."
ICONS="home settings wifi wifi_off network_wifi_1_bar network_wifi_2_bar network_wifi_3_bar signal_wifi_4_bar bluetooth
bluetooth_connected bluetooth_disabled volume_up volume_down volume_mute volume_off mic mic_off notifications notifications_off
notifications_active power_settings_new restart_alt logout lock bedtime dark_mode light_mode nightlight play_arrow pause skip_next
skip_previous fast_forward fast_rewind music_note search close check apps grid_view wallpaper image palette brightness_medium
brightness_high brightness_low battery_full battery_charging_full battery_0_bar battery_1_bar battery_2_bar battery_3_bar
battery_4_bar battery_5_bar battery_6_bar bolt cloud sunny partly_cloudy_day partly_cloudy_night rainy weather_snowy thunderstorm
foggy clear_night calendar_today schedule timer refresh add remove delete more_horiz keyboard_arrow_up keyboard_arrow_down
chevron_right chevron_left expand_more memory speed thermostat developer_board hard_drive screenshot_region videocam stop
do_not_disturb_on airplanemode_active sports_esports shuffle repeat person terminal folder public code edit coffee desktop_windows
keyboard tune graphic_eq ac_unit water_drop air rocket_launch shield lan"
tmp=$(mktemp -d)
for n in $ICONS; do
  for v in "" "_fill1"; do
    curl -fsS "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/$n/materialsymbolsrounded/${n}${v}_24px.svg" -o "$tmp/${n}${v}.svg" || rm -f "$tmp/${n}${v}.svg"
  done
done
python3 - "$tmp" > src/icons_data.rs <<'PY'
import os, re, sys
d = sys.argv[1]
out = []
for f in sorted(os.listdir(d)):
    s = open(os.path.join(d, f)).read()
    out.append((f[:-4], " ".join(re.findall(r' d="([^"]+)"', s))))
out.sort()
print("// Material Symbols Rounded (Google, Apache-2.0), viewBox 0 -960 960 960.")
print("// Generated by tools/fetch-icons.sh; sorted for binary search.")
print("pub const ICONS: &[(&str, &str)] = &[")
for n, p in out:
    print(f'    ("{n}", "{p}"),')
print("];")
PY
rm -rf "$tmp"
echo "wrote src/icons_data.rs"
